"""
Scope Doc §13A / Workflow Step 13.2: the governed PDLF step-completion
write path.

Real scope boundary, deliberately drawn before writing any code: querying
GBrain for related content, reading it, and forming a genuine
confidence/contradiction judgment (Scope Doc §11A) is the SUBMITTING
AGENT's job -- OpenCode/PDLF's own live, agentic work, requiring a real
conversation to do honestly. It cannot be built or honestly simulated
inside this repository -- the same territory mb-submit-memory (Phase 14)
already sits in, deferred for the identical reason.

What genuinely belongs here, and is pure, testable, dependency-free
Python: taking an ALREADY-ASSESSED artifact -- content, confidence, and
contradiction status genuinely determined by the calling agent -- and
submitting it correctly, individually, through the real, governed
pipeline, using the pdlf_step_sync credential. This module never computes
a confidence score or a contradiction determination itself; it only ever
passes through what the caller supplies, exactly as Scope Doc §11A
requires. Mirrors self_healing.submit_detected_pattern()'s exact shape
(Step 11.2), for a different writer identity.
"""
import os
from typing import Optional

from .api import submit_candidate, CandidateSubmissionRequest
from .models import Content, Confidence, Contradiction


def submit_pdlf_artifact(
    owning_project: str,
    content_text: str,
    memory_type: str,
    source_ref: str,
    confidence_score: float,
    confidence_method: str,
    contradiction: Optional[Contradiction] = None,
) -> dict:
    """
    Submits ONE PDLF step artifact through the real, governed pipeline --
    the exact same submit_candidate() function POST /memory/candidate
    calls, per Workflow Step 13.2's explicit requirement (no
    special-cased write path, same discipline as self_healing's own
    submission in Step 11.2).

    Each artifact a finished PDLF step produced is submitted individually,
    via its own separate call to this function -- never batched into one
    candidate. A step producing multiple artifacts (e.g. Step 16:
    CONTEXT.md plus zero or more ADRs) means multiple separate calls,
    each independently decided by decide_path().

    confidence_score/confidence_method/contradiction are REQUIRED-in-
    spirit parameters, even though contradiction has a technical default
    of None -- per Scope Doc §11A, the caller must have genuinely
    queried GBrain and formed a real judgment before calling this, never
    pass a placeholder value. This function has no way to enforce that
    the caller actually did the query-and-read step; it can only ensure
    it never silently invents a value on the caller's behalf.

    retention is "permanent" -- PDLF step artifacts (glossary terms,
    ADRs) are durable, canonical project record, the same category as
    propose_policy()'s own submissions, not ephemeral or long_term.
    source_type is "agent_trace" -- generated by an OpenCode agent's own
    process, not a human directly, the same classification used for
    self_healing's submissions in Step 11.2.
    """
    credential = os.environ["MEMORY_GOVERNOR_WRITER_PDLF_STEP_SYNC"]

    req = CandidateSubmissionRequest(
        owning_project=owning_project,
        visibility="project_local",
        retention="permanent",
        memory_type=memory_type,
        content=Content(text=content_text),
        source_type="agent_trace",
        source_ref=source_ref,
        policy_version="v1",
        confidence=Confidence(score=confidence_score, method=confidence_method),
        contradiction=contradiction,
    )

    return submit_candidate(req, credential)
